// Rebuilds app.js from content.js, chat-client.js and src/page.js.
// app.js is a single classic script so the page also works when opened from disk.
// Usage: node scripts/build-app.mjs
import {readFileSync, writeFileSync} from 'node:fs';

const root = new URL('..', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const stripExports = text => text.replace(/^export (const|function|async function) /gm, '$1 ');
const body = [stripExports(read('content.js')), stripExports(read('chat-client.js')), read('src/page.js')].join('\n\n');
writeFileSync(new URL('app.js', root), `// Generated by scripts/build-app.mjs — edit content.js, chat-client.js or src/page.js instead.\n(() => {\n'use strict';\n${body}\n})();\n`);
console.log('Wrote app.js');
